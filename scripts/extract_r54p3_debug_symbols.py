#!/usr/bin/env python3
"""
Extracts debug symbol names from .gnu_debugdata (LZMA-compressed mini-ELF .symtab)
and .dynsym of ddk/libGLES_mali.so (r54p3-00eac0-6eda07), demangles C++
names via c++filt, and emits src/aot/generated/r54p3_debug_symbols.h for
zero-overhead O(log N) lookup in aot_so_profiler.hpp and mali_llvm_passes.cpp.
"""
import lzma
import os
import subprocess
import tempfile
from elftools.elf.elffile import ELFFile


def main():
    so_path = "ddk/libGLES_mali.so"
    out_path = "src/aot/generated/r54p3_debug_symbols.h"
    if not os.path.exists(so_path):
        raise FileNotFoundError(so_path)

    with open(so_path, "rb") as f:
        elf = ELFFile(f)
        sec = elf.get_section_by_name(".gnu_debugdata")
        if sec is None:
            raise RuntimeError(".gnu_debugdata section not found")
        raw_mini_elf = lzma.decompress(sec.data())

    with tempfile.NamedTemporaryFile(delete=False, suffix=".elf") as tf:
        tf.write(raw_mini_elf)
        tf_path = tf.name

    try:
        nm_out = subprocess.check_output(["nm", "-n", "--defined-only", tf_path], text=True)
    finally:
        os.unlink(tf_path)

    rva_to_mangled = {}
    for line in nm_out.splitlines():
        parts = line.split()
        if len(parts) < 3:
            continue
        addr_hex, sym_type, sym_name = parts[0], parts[1], parts[2]
        if sym_type.lower() not in ("t", "w"):
            continue
        rva = int(addr_hex, 16)
        if rva == 0:
            continue
        # Prefer non-compiler-generated / shorter names if multiple aliases share RVA
        if rva not in rva_to_mangled or len(sym_name) < len(rva_to_mangled[rva]):
            rva_to_mangled[rva] = sym_name

    sorted_rvas = sorted(rva_to_mangled.keys())
    mangled_list = [rva_to_mangled[r] for r in sorted_rvas]

    # Batch demangle with c++filt
    demangled_out = subprocess.check_output(
        ["c++filt"],
        input="\n".join(mangled_list) + "\n",
        text=True,
    )
    demangled_list = demangled_out.splitlines()

    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    lines = [
        "#pragma once",
        "// AUTO-GENERATED BY scripts/extract_r54p3_debug_symbols.py — DO NOT EDIT BY HAND.",
        f"// Source: {so_path} (.gnu_debugdata, {len(sorted_rvas)} function symbols).",
        "#include <cstddef>",
        "#include <cstdint>",
        "#include <cstring>",
        "",
        "struct R54p3DebugSymbolEntry {",
        "    uint32_t    rva;",
        "    const char* name;",
        "};",
        "",
        f"static constexpr size_t kR54p3DebugSymbolCount = {len(sorted_rvas)};",
        "",
        "static const R54p3DebugSymbolEntry kR54p3DebugSymbols[kR54p3DebugSymbolCount] = {",
    ]
    for rva, dem in zip(sorted_rvas, demangled_list):
        # Strip parameter list for huge C++ signatures to keep logs crisp, keep class::method
        short = dem.strip()
        if len(short) > 96:
            paren = short.find("(")
            if paren > 0:
                short = short[:paren] + "(...)"
        short = short.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'    {{0x{rva:08x}U, "{short}"}},')
    lines += [
        "};",
        "",
        "static inline const char* r54p3_lookup_debug_symbol_by_va(uint64_t fn_va) {",
        "    static constexpr uint64_t kImageBase = 0x400000000ULL;",
        "    uint64_t rva64 = (fn_va >= kImageBase) ? (fn_va - kImageBase) : fn_va;",
        "    if (rva64 > 0xFFFFFFFFULL) return nullptr;",
        "    uint32_t rva = static_cast<uint32_t>(rva64);",
        "    size_t lo = 0;",
        "    size_t hi = kR54p3DebugSymbolCount;",
        "    while (lo < hi) {",
        "        size_t mid = lo + ((hi - lo) >> 1);",
        "        uint32_t cur = kR54p3DebugSymbols[mid].rva;",
        "        if (cur == rva) return kR54p3DebugSymbols[mid].name;",
        "        if (cur < rva) lo = mid + 1;",
        "        else hi = mid;",
        "    }",
        "    return nullptr;",
        "}",
        "",
    ]
    with open(out_path, "w") as f:
        f.write("\n".join(lines))
    print(f"Generated {out_path} with {len(sorted_rvas)} demangled .gnu_debugdata symbols.")


if __name__ == "__main__":
    main()
