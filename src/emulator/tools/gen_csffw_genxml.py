#!/usr/bin/env python3
"""Generate CSF instruction decode helpers from Panfrost genxml.

Parses `mesa/src/panfrost/genxml/v11.xml` (the pinned Panfrost v11 XML) and
emits `src/emulator/csffw_genxml_decode.h`, which provides:

  * `CS_OPCODE_*` constants for every `<enum name="CS Opcode">` value.
  * `csffw_opcode_name()` for tracing.
  * Per-opcode field accessors `cs_<struct>_<field>(uint64_t insn)` derived
    from the `<struct name="CS ...">` bit layouts (with `minus`/`shr`/`log2`
    modifiers inverted so the accessor returns the logical value).

The accessors replace hand-written bit shifts in `src/emulator/lifted_csffw.c`
so the lifting stays in sync with the hardware XML.

Usage:
    python3 tools/gen_csffw_genxml.py [--xml PATH] [--out PATH]
"""

import argparse
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_XML = ROOT / "specs" / "panfrost" / "v11.xml"
DEFAULT_OUT = ROOT / "src" / "emulator" / "generated" / "csffw_genxml_decode.h"


def snake(name: str) -> str:
    """Turn a genxml name into a C identifier fragment."""
    s = name.strip().lower()
    s = re.sub(r"[^a-z0-9]+", "_", s)
    s = re.sub(r"_+", "_", s).strip("_")
    if not s:
        s = "x"
    if s[0].isdigit():
        s = "_" + s
    return s


def parse_start(start: str) -> int:
    """genxml `start` is either a bit offset or `word:bit` (word*32+bit)."""
    if ":" in start:
        word, bit = start.split(":")
        return int(word) * 32 + int(bit)
    return int(start)


def parse_modifier(mod: str):
    """Return (kind, arg) for a genxml modifier, or None."""
    if not mod:
        return None
    m = re.match(r"^(shr|minus|align)\((\d+)\)$", mod)
    if m:
        return (m.group(1), int(m.group(2)))
    if mod == "log2":
        return ("log2", 0)
    return None


def field_expr(bit: int, size: int, modifier) -> str:
    """C expression extracting the logical field value from `insn`."""
    mask = (1 << size) - 1
    if bit == 0:
        raw = f"(insn & 0x{mask:x}ULL)"
    else:
        raw = f"((insn >> {bit}) & 0x{mask:x}ULL)"
    if modifier is None:
        return f"(uint64_t){raw}"
    kind, arg = modifier
    if kind == "minus":
        return f"((uint64_t){raw} + {arg}ULL)"
    if kind == "shr":
        return f"((uint64_t){raw} << {arg})"
    if kind == "log2":
        return f"(1ULL << (uint64_t){raw})"
    if kind == "align":
        return f"(uint64_t){raw}"
    return f"(uint64_t){raw}"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--xml", default=str(DEFAULT_XML))
    ap.add_argument("--out", default=str(DEFAULT_OUT))
    args = ap.parse_args()

    xml_path = Path(args.xml)
    out_path = Path(args.out)
    if not xml_path.is_file():
        print(f"error: XML not found: {xml_path}", file=sys.stderr)
        return 1

    root = ET.parse(xml_path).getroot()

    # 1. CS Opcode enum.
    opcodes = []
    for enum in root.findall("enum"):
        if enum.get("name") != "CS Opcode":
            continue
        for value in enum.findall("value"):
            opcodes.append((value.get("name"), int(value.get("value"))))
    if not opcodes:
        print("error: no 'CS Opcode' enum in XML", file=sys.stderr)
        return 1

    # 2. CS structs (name -> fields), keyed by their Opcode default.
    structs = []
    for st in root.findall("struct"):
        name = st.get("name", "")
        if not name.startswith("CS "):
            continue
        fields = []
        opcode_default = None
        for f in st.findall("field"):
            fname = f.get("name")
            bit = parse_start(f.get("start"))
            size = int(f.get("size"))
            modifier = parse_modifier(f.get("modifier"))
            fields.append((fname, bit, size, modifier))
            if fname == "Opcode":
                opcode_default = f.get("default")
        structs.append((name, opcode_default, fields))

    lines = []
    lines.append("/*")
    lines.append(" * AUTO-GENERATED by tools/gen_csffw_genxml.py from")
    lines.append(" * mesa/src/panfrost/genxml/v11.xml. DO NOT EDIT.")
    lines.append(" *")
    lines.append(" * CSF instruction opcode constants and field accessors derived from")
    lines.append(" * the Panfrost v11 genxml bit layouts. `insn` is the full 64-bit CSF")
    lines.append(" * instruction: insn = ((uint64_t)cmd_hi << 32) | cmd_lo.")
    lines.append(" */")
    lines.append("#ifndef CSFFW_GENXML_DECODE_H")
    lines.append("#define CSFFW_GENXML_DECODE_H")
    lines.append("")
    lines.append("#include <stdint.h>")
    lines.append("")
    lines.append("#ifdef __cplusplus")
    lines.append('extern "C" {')
    lines.append("#endif")
    lines.append("")
    lines.append("/* --- CS Opcode enum (v11.xml: <enum name=\"CS Opcode\">) --- */")
    for name, value in opcodes:
        lines.append(f"#define CS_OPCODE_{name} {value}")
    lines.append("")
    lines.append("static inline const char *csffw_opcode_name(uint32_t opcode)")
    lines.append("{")
    lines.append("    switch (opcode) {")
    for name, value in opcodes:
        lines.append(f'    case CS_OPCODE_{name}: return "{name}";')
    lines.append('    case 0x80: return "NOP_TRAP";')
    lines.append('    default: return "CS_UNKNOWN";')
    lines.append("    }")
    lines.append("}")
    lines.append("")

    # 3. Field accessors.
    for sname, opcode_default, fields in structs:
        sid = snake(sname[3:])  # strip "CS "
        lines.append(f"/* {sname}"
                     + (f" (opcode {opcode_default})" if opcode_default else "")
                     + " */")
        for fname, bit, size, modifier in fields:
            fid = snake(fname)
            expr = field_expr(bit, size, modifier)
            mod_note = ""
            if modifier:
                kind, arg = modifier
                mod_note = f"  /* modifier: {kind}({arg}) */" if kind != "log2" else "  /* modifier: log2 */"
            lines.append(f"static inline uint64_t cs_{sid}_{fid}(uint64_t insn) "
                         f"{{ return {expr}; }}{mod_note}")
        lines.append("")

    lines.append("#ifdef __cplusplus")
    lines.append("}")
    lines.append("#endif")
    lines.append("")
    lines.append("#endif /* CSFFW_GENXML_DECODE_H */")
    lines.append("")

    out_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"generated {out_path.relative_to(ROOT)}: "
          f"{len(opcodes)} opcodes, {len(structs)} CS structs, "
          f"{sum(len(f) for _, _, f in structs)} field accessors")
    return 0


if __name__ == "__main__":
    sys.exit(main())
